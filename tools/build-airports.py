#!/usr/bin/env python3
"""Regenerate app/js/airports.js from the OurAirports dataset (public domain).

    curl -o /tmp/airports.csv https://davidmegginson.github.io/ourairports-data/airports.csv
    python3 tools/build-airports.py /tmp/airports.csv > app/js/airports.js
"""
import csv
import json
import sys

KEEP = ("large_airport", "medium_airport", "small_airport")
SIZE = {"large_airport": 0, "medium_airport": 1, "small_airport": 2}

out = []
with open(sys.argv[1], encoding="utf-8") as f:
    for r in csv.DictReader(f):
        if not r["iata_code"] or r["scheduled_service"] != "yes" or r["type"] not in KEEP:
            continue
        out.append([
            r["iata_code"],
            r["icao_code"] or r["ident"],
            r["name"].replace(" International", " Intl"),
            r["municipality"],
            r["iso_country"],
            round(float(r["latitude_deg"]), 4),
            round(float(r["longitude_deg"]), 4),
            SIZE[r["type"]],
        ])
out.sort(key=lambda a: a[0])

print("// Generated by tools/build-airports.py from OurAirports. [iata, icao, name, city, country, lat, lon, size]")
print("window.RR = window.RR || {};")
print("RR.AIRPORTS = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";")
